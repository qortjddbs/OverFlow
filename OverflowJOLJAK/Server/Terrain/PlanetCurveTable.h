    // Catmull-Rom 보간. 균일 격자라 선형보간보다 오차가 수천 배 작다.
    inline double Eval(double t)
    {
        if (t <= MIN_T)                    return SAMPLES[0];
        const double maxT = MIN_T + (NUM - 1) * STEP;
        if (t >= maxT)                     return SAMPLES[NUM - 1];

        const double f = (t - MIN_T) / STEP;
        int i = static_cast<int>(f);
        if (i < 0)        i = 0;
        if (i > NUM - 2)  i = NUM - 2;

        const double a = f - i;

        const int i0 = (i - 1 < 0)       ? 0       : i - 1;
        const int i1 = i;
        const int i2 = i + 1;
        const int i3 = (i + 2 > NUM - 1) ? NUM - 1 : i + 2;

        const double p0 = SAMPLES[i0];
        const double p1 = SAMPLES[i1];
        const double p2 = SAMPLES[i2];
        const double p3 = SAMPLES[i3];

        const double a2 = a * a;
        const double a3 = a2 * a;

        return 0.5 * ((2.0 * p1)
                    + (-p0 + p2) * a
                    + (2.0 * p0 - 5.0 * p1 + 4.0 * p2 - p3) * a2
                    + (-p0 + 3.0 * p1 - 3.0 * p2 + p3) * a3);
    }
